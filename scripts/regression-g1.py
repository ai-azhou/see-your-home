#!/usr/bin/env python3
"""Offline integration regression: actual render passes, prompts, drift, color and CLI JSON."""
import importlib.util
import json
import subprocess
import sys
from pathlib import Path
import numpy as np
from PIL import Image

skill, kit = map(Path, sys.argv[1:3])
script = skill/'scripts'
camera = kit/'room_r-living-white.camera.json'
clay = kit/'room_r-living-white.png'
meta = json.loads(camera.read_text())
for template in ('结构参考','风格照片'):
    result = subprocess.check_output([sys.executable, str(script/'gen_prompt.py'), str(camera),
        '--style','奶油原木：浅橡木地板、奶油白墙', '--template',template], text=True)
    assert '{' not in result and '不加窗帘、百叶、纱帘' in result
    assert '浅橡木地板' in result and '960×540' in result
    for o in meta['openings']:
        assert o['name'] in result and f'{100*o["bbox_xyxy"][0]/meta["width"]:.0f}%' in result
    assert ('图4' in result) == (template == '风格照片')
    print('prompt:',template,'PASS')
    white = subprocess.check_output([sys.executable, str(script/'gen_prompt.py'), str(camera),
        '--style','奶油原木风', '--template',template,'--white-only'], text=True)
    assert '图3' not in white and '图4' not in white
    assert ('图2' in white) == (template == '风格照片')
    assert '奶油原木风' in white and '不加窗帘、百叶、纱帘' in white
    assert '画面可见门窗共' in white and '960×540' in white
    print('prompt --white-only:',template,'PASS')

# Scale about the center by 1.10, translate right/down by 10%, then add seeded noise.
im = Image.open(clay).convert('RGB'); w,h=im.size
shifted=im.transform((w,h),Image.Transform.AFFINE,
    (1/1.1,0,w/2-(w/2+.1*w)/1.1,0,1/1.1,h/2-(h/2+.1*h)/1.1),
    resample=Image.Resampling.BICUBIC,fillcolor='white')
noise=np.random.default_rng(42).normal(0,6,(h,w,3))
bad=kit/'drift-noise.png'; Image.fromarray(np.clip(np.asarray(shifted,dtype=float)+noise,0,255).astype('uint8')).save(bad)
# Pure color reference exercises palette fallback to fewer than three clusters.
style=kit/'style.png'; Image.new('RGB',(48,32),(210,190,160)).save(style)
output=kit/'generation-scores.json'
subprocess.run([sys.executable,str(script/'gen_score.py'),'--camera',str(camera),str(clay),str(bad),
    '--style-photo',str(style),'--triptych-dir',str(kit/'triptychs'),'-o',str(output)],check=True)
r=json.loads(output.read_text(),parse_constant=lambda v: (_ for _ in ()).throw(ValueError(v)))
good,drift=r['images']
assert good['pass'] and abs(good['S']-1)<1e-10 and good['opening_score']==1,good
assert not drift['pass'] and drift['S']<.6,drift
assert len(list((kit/'triptychs').glob('*.jpg')))==2
assert good['style']['mean_delta_e2000'] is not None
print('white model:',good['S'],'PASS; drift + 10% scale + noise:',drift['S'],'REJECT')

spec=importlib.util.spec_from_file_location('gen_score',script/'gen_score.py')
m=importlib.util.module_from_spec(spec);spec.loader.exec_module(m)
# Published Sharma test pairs, not generated by the implementation under test.
pairs=[([50,2.6772,-79.7751],[50,0,-82.7485],2.0425),
       ([50,3.1571,-77.2803],[50,0,-82.7485],2.8615),
       ([50,0,0],[50,-1,2],2.3669)]
for a,b,expected in pairs:
    assert abs(float(m.deltaE_ciede2000(a,b))-expected)<.0001
assert np.allclose(m.rgb2lab(np.array([[1.,1.,1.],[0,0,0]]))[:,0],[100,0],atol=.001)
# EDT against direct distances; irregular edge layout probes both axes.
edges=np.zeros((13,17),bool);edges[2,4]=True;edges[10,14]=True
Y,X=np.indices(edges.shape)
expected=np.minimum(np.hypot(Y-2,X-4),np.hypot(Y-10,X-14))
assert np.allclose(m.edt(~edges),expected)
assert not m.canny(Image.new('RGB',(m.W,m.H),'white')).any()
# Different aspect ratios must be center-cropped, never stretched.
m.W,m.H=960,600
square=kit/'square.png';Image.new('RGB',(500,500),'white').save(square)
res,size,note=m.load_rgb(square);assert res.size==(960,600) and note and size==(500,500)
print('CIEDE2000 / Lab / exact EDT / flat-image Canny / aspect crop: PASS')
